#!/usr/bin/env node
/* Builds assets/search-index.js from the module pages, glossary and calculators.
   Also gives every <h2> in modules/*.html a stable id (once) so search results can deep-link.
   Run after editing any content:   node scripts/build-search.js
   (tests/search.test.js fails if the committed index is stale.) */
"use strict";
const fs = require("fs");
const path = require("path");
const vm = require("vm");

const ROOT = path.resolve(__dirname, "..");
const load = (file, key) => {
  const sandbox = { window: {} };
  vm.runInNewContext(fs.readFileSync(path.join(ROOT, file), "utf8"), sandbox);
  return sandbox.window[key];
};

const ENT = { amp: "&", lt: "<", gt: ">", quot: '"', nbsp: " ", mdash: "-", ndash: "-", rsquo: "'", lsquo: "'", times: "x", minus: "-" };
const decode = (s) => s.replace(/&(#x?[0-9a-f]+|[a-z]+);/gi, (m, e) => {
  if (e[0] === "#") return String.fromCodePoint(e[1] === "x" || e[1] === "X" ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
  return e.toLowerCase() in ENT ? ENT[e.toLowerCase()] : m;
});
const text = (html) => decode(html.replace(/<(script|style)[\s\S]*?<\/\1>/gi, " ").replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();
const slug = (s) => text(s).toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "").slice(0, 60) || "section";

function build() {
  const modules = load("assets/modules.js", "FAA_MODULES");
  const glossary = load("assets/glossary.js", "FAA_GLOSSARY");
  const entries = [];

  for (const m of modules) {
    const file = path.join(ROOT, "modules", m.file);
    let html = fs.readFileSync(file, "utf8");
    // 1) stable ids on h2s that lack one
    const used = new Set([...html.matchAll(/\bid="([^"]+)"/g)].map((x) => x[1]));
    const fixed = html.replace(/<h2(\s[^>]*)?>([\s\S]*?)<\/h2>/g, (all, attrs, inner) => {
      if (attrs && /\bid=/.test(attrs)) return all;
      let id = slug(inner), n = 2;
      while (used.has(id)) id = `${slug(inner)}-${n++}`;
      used.add(id);
      return `<h2${attrs || ""} id="${id}">${inner}</h2>`;
    });
    if (fixed !== html) { fs.writeFileSync(file, fixed); html = fixed; }

    // 2) one entry per h2 section (plus the intro before the first h2)
    const main = html.slice(html.indexOf("<main>") + 6, html.indexOf("</main>"));
    const parts = main.split(/(?=<h2[\s>])/);
    parts.forEach((part, i) => {
      const hm = part.match(/^<h2[^>]*?(?:\sid="([^"]+)")?[^>]*>([\s\S]*?)<\/h2>/);
      const heading = hm ? text(hm[2]) : m.title;
      const id = hm ? hm[1] : "";
      entries.push({ k: "module", m: m.id, t: `${m.id} · ${m.title}`, h: heading, u: `modules/${m.file}${id ? "#" + id : ""}`, x: text(part.replace(/^<h2[\s\S]*?<\/h2>/, "")) });
    });
  }

  for (const [term, def, mod] of glossary) {
    entries.push({ k: "term", m: mod, t: "Glossary", h: term, u: `glossary.html?q=${encodeURIComponent(term)}`, x: def });
  }

  const tools = [
    ["nav", "NAV and NAV per share calculator", "net asset value assets minus liabilities shares"],
    ["accrual", "Bond accrued interest calculator", "accrued interest coupon day count 30/360 ACT/360 ACT/365 ACT/ACT clean dirty price"],
    ["perf", "Management and performance fee calculator", "management fee performance fee incentive high-water mark HWM hurdle soft hard crystallization"],
    ["wf", "Private-fund waterfall calculator", "waterfall preferred return pref catch-up carried interest carry GP LP distribution"],
    ["ret", "IRR, MOIC, DPI, TVPI calculator", "IRR XIRR MOIC DPI RVPI TVPI returns private equity"],
    ["alloc", "P&L allocation calculator", "allocate profit loss investors capital pro rata weight"],
    ["je", "Journal entry trainer", "journal entry debit credit practice buy sell accrual dividend redemption unrealized"]
  ];
  for (const [id, title, kw] of tools) entries.push({ k: "tool", m: "", t: "Calculators", h: title, u: `tools.html#${id}`, x: kw });
  return entries;
}

function render(entries) {
  return "/* GENERATED by scripts/build-search.js - do not edit by hand. */\nwindow.FAA_INDEX = " + JSON.stringify(entries) + ";\n";
}

if (require.main === module) {
  const entries = build();
  fs.writeFileSync(path.join(ROOT, "assets", "search-index.js"), render(entries));
  console.log(`search index: ${entries.length} entries`);
}
module.exports = { build, render };
